#ifndef __ACT_H__
#define __ACT_H__

#include "stm32f10x.h"
#include <stdint.h>

/*==============================================================================
 * 固定动作（act）—— 2026-11-14 新增
 *
 * 用途：循迹过程中，灰度阵列会扫到一些“形状”，说明车已经到了赛道上的固定
 *       位置（直角弯、横线、出线……）。这些位置不能靠位置环硬掰，必须执行
 *       事先排好的固定动作。动作按“动作表”的顺序依次执行，见 Act.c 里的
 *       s_act_plan[]。
 *
 * 触发条件（16 路，p0 最左、p15 最右；1 = 扫到白线，黑线下是“扫到线”）：
 *   A. 至少 12 路扫不到线（扫到的 ≤4 路）
 *   B. 左 8 路里 ≥6 路扫到线，且右 8 路里 ≤1 路扫到线
 *   C. 右 8 路里 ≥6 路扫到线，且左 8 路里 ≤1 路扫到线
 *   D. 至少 12 路扫到线
 * 四条**都只是触发**，不区分是哪一条：每触发一次，就从动作表里取下一格执行。
 * 表走完以后再遇到触发 ⇒ 自动停车（LED 报警）。
 *
 * 触发节奏：命中 1 拍（2ms）就触发——单次采样符合即认（2026-11-14 用户要求）；
 * 一次动作结束后，必须等四条条件都不成立并保持 ACT_REARM_QUIET_TICKS(5) 拍，
 * 才允许下一次触发，否则同一条条件会一路把动作表吃光。
 *
 * 现有动作：
 *   ACT_TL —— 直角左转：左轮刹停（占空比 0，半桥下管常通 = 短路制动），
 *             右轮速度环闭环 1200 mm/s；左右编码器之差（右−左）达到
 *             “转 90° 对应的弧长”就完成：π/2 × 130 mm ≈ 204.2 mm ≈ 11125 counts
 *             （54476 counts/m）。完成后两个速度环复位、起步斜坡重爬，回循迹。
 *   ACT_TR —— 直角右转：镜像（右轮刹停，左轮 1200 mm/s，差 = 左−右）。
 *
 * 串口：'3' = 单独测一次 ACT_TL，'4' = 单独测一次 ACT_TR。台架测试用，不消耗
 *       动作表；测完电机断电回 IDLE。
 *============================================================================*/

#define ACT_TL              1u   /* 直角左转 */
#define ACT_TR              2u   /* 直角右转 */

/* 动作表里的一格 = 上面两个值之一。动作表本体在 Act.c，改顺序只改那里。 */

/* 延迟事件：2ms 环形里不能直接 printf（一行 ~5ms），登记在信箱里由串口任务打印 */
#define ACT_EVT_NONE        0u
#define ACT_EVT_START       1u   /* 动作开始 */
#define ACT_EVT_DONE        2u   /* 正常完成（编码器差到位） */
#define ACT_EVT_TIMEOUT     3u   /* 超时没转到位 ⇒ 停电机 + 报警 */
#define ACT_EVT_PLAN_END    4u   /* 动作表已用完又遇到触发 ⇒ 自动停车 */

/* 初始化（只在 App_HardwareInit 之后、进循迹之前调一次） */
void Act_Init(void);

/* 清状态并让动作表从头开始（切模式时调用；正在执行的动作会被直接放弃） */
void Act_Reset(void);

/* 循迹时每 2ms 调一次（Act_IsRunning()==0 时才检测触发） */
void Act_Poll(void);

/* 每 2ms 调一次；动作执行中才真正动电机 */
void Act_Update(void);

/* 是否正在执行动作（Car_Control_Update 用它决定跑 act 还是跑位置环） */
uint8_t Act_IsRunning(void);

/* 串口 '3'/'4'：单独执行一次动作（台架测试，不消耗动作表）。返回 1 = 已启动 */
uint8_t Act_TestStart(uint8_t act);

/* 取一条延迟事件（串口任务轮询）。返回 ACT_EVT_*，没有事件返回 ACT_EVT_NONE */
uint8_t Act_TakeEvent(uint8_t *act_id, int32_t *diff_counts, uint16_t *elapsed_ms);

/* 动作名（"act_tl" / "act_tr" / "act?"），打印用 */
const char *Act_GetName(uint8_t act_id);

#endif /* __ACT_H__ */
